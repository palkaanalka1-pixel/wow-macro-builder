function getLocale() {
  const saved = localStorage.getItem(WOW_LOCALE_KEY);
  return saved === 'en' ? 'en' : 'ru';
}

function setLocale(locale) {
  localStorage.setItem(WOW_LOCALE_KEY, locale === 'en' ? 'en' : 'ru');
}

function t(key) {
  const locale = getLocale();
  const parts = key.split('.');
  let val = WOW_I18N[locale];
  for (const p of parts) val = val?.[p];
  if (val === undefined) {
    val = WOW_I18N.ru;
    for (const p of parts) val = val?.[p];
  }
  return val ?? key;
}

function getClassName(classId, locale = getLocale()) {
  return WOW_I18N[locale].classes[classId] || WOW_SPELLS_DB[classId]?.name || classId;
}

function getSpecName(specId, locale = getLocale()) {
  return WOW_I18N[locale].specs[specId] || specId;
}

function getCategoryLabel(category, locale = getLocale()) {
  return WOW_I18N[locale].categories[category] || category;
}

function getSpellDisplayName(spell, locale = getLocale()) {
  if (!spell) return '';
  if (locale === 'en') return spell.nameEn || SPELL_NAME_EN[spell.nameRu] || spell.nameRu || spell.name;
  return spell.nameRu || spell.name;
}

